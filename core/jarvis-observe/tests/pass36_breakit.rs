fn screen_with(label: &str, role: Role) -> CompactScreen {
    CompactScreen {
        app_bundle_id: "com.example.app".to_owned(),
        app_name: Some("Example".to_owned()),
        size: jarvis_proto::fixtures::IPHONE_SIZE,
        keyboard_visible: false,
        elements: vec![Element {
            index: 1,
            role,
            label: label.to_owned(),
            value: None,
            placeholder: None,
            frame: Rect::new(16.0, 120.0, 361.0, 44.0),
            enabled: true,
            focused: false,
            selected: false,
            secure: false,
            fingerprint: 1,
        }],
        cues: Default::default(),
    }
}

/// The labels of [`ORDINARY`] whose look-alike readings give a category their own words do
/// not, with the old and the gained categories.
fn gained() -> Vec<String> {
    let mut out = Vec::new();
    for &label in ORDINARY {
        for role in [Role::Button, Role::Cell, Role::Link, Role::StaticText] {
            let risks = tap_reading_risks(
                &Action::Tap { element: 1 },
                &screen_with(label, role.clone()),
            );
            let Some((&old, rest)) = risks.split_first() else {
                continue;
            };
            let new: Vec<RiskCategory> = rest
                .iter()
                .copied()
                .filter(|&c| c != old && c != RiskCategory::None)
                .collect();
            if !new.is_empty() {
                out.push(format!("{label:?} as {role:?}: {old:?} -> also {new:?}"));
            }
        }
    }
    out
}

/// Sound (new coverage): none of the 252 ordinary labels, as a button, a cell, a link or a
/// text, gains a category by a look-alike reading (so no policy refuses them anew).
#[test]
fn sound_ordinary_labels_gain_no_category_by_a_reading() {
    assert!(ORDINARY.len() >= 150, "{}", ORDINARY.len());
    let gained = gained();
    assert!(gained.is_empty(), "{}", gained.join("\n"));
}
