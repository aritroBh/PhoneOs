/// Labels whose category the look-alike sets change, in survey order, and why a reader sees
/// the risk word in each (every role, both apps): a handle written with a zero for an `o`
/// (`@bl0ck` is "@block": AccountChange), and words that spell a risk phrase without its
/// space, which the sets read like `DeleteAccount` (`Callback` is "call back": Call,
/// `Shutdown` "shut down" and `Turnoff` "turn off": SystemSetting, `Topup` "top up" and
/// `Cashout` "cash out": Payment, `Golive` "go live": PublicPost). Every other label — the
/// all-caps words, the capital-`I` and `l` words, `Mall`/`Mali`/`MAIL`, the digits and
/// symbols beside letters, the emails and prices — classifies exactly as before.
const EXPECTED: &[&str] = &[
    "@bl0ck", "Callback", "Shutdown", "Topup", "Cashout", "Golive", "Turnoff",
];

fn screen_with(label: &str, role: Role, bundle: &str) -> CompactScreen {
    CompactScreen {
        app_bundle_id: bundle.to_owned(),
        app_name: Some("Example".to_owned()),
        size: jarvis_proto::fixtures::IPHONE_SIZE,
        keyboard_visible: false,
        elements: vec![Element {
            index: 1,
            role,
            label: label.to_owned(),
            value: None,
            placeholder: None,
            frame: Rect::new(16.0, 120.0, 361.0, 44.0),
            enabled: true,
            focused: false,
            selected: false,
            secure: false,
            fingerprint: 1,
        }],
        cues: Default::default(),
    }
}

/// `label: old -> new (roles)` for every label the sets change.
fn changed() -> Vec<String> {
    let mut out = Vec::new();
    for &label in LABELS {
        let mut how: Vec<String> = Vec::new();
        for role in [Role::Button, Role::Cell, Role::Link, Role::StaticText] {
            for bundle in ["com.example.app", "com.apple.Preferences"] {
                let risks = tap_reading_risks(
                    &Action::Tap { element: 1 },
                    &screen_with(label, role.clone(), bundle),
                );
                let Some((&old, rest)) = risks.split_first() else {
                    continue;
                };
                let new: Vec<RiskCategory> = rest
                    .iter()
                    .copied()
                    .filter(|&c| c != old && c != RiskCategory::None)
                    .collect();
                if !new.is_empty() {
                    how.push(format!("{role:?} in {bundle}: {old:?} -> {new:?}"));
                }
            }
        }
        if !how.is_empty() {
            out.push(format!("{label:?}: {}", how.join("; ")));
        }
    }
    out
}

#[test]
fn ordinary_labels_change_only_where_a_reader_sees_the_risk_word() {
    assert!(LABELS.len() >= 400, "{}", LABELS.len());
    let got = changed();
    for g in &got {
        println!("{g}");
    }
    let names: Vec<String> = got
        .iter()
        .map(|g| g.split(": ").next().unwrap_or_default().to_owned())
        .collect();
    let want: Vec<String> = EXPECTED.iter().map(|w| format!("{w:?}")).collect();
    assert_eq!(names, want, "{}", got.join("\n"));
}
